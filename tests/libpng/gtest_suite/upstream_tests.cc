// GoogleTest wrappers around the upstream libpng correctness validator
// (upstream/pngvalid.c, see ../README.md for provenance). pngvalid is libpng's
// own ~12k-line validator: it self-generates PNG images across bit depths,
// colour types, and interlacing, writes and reads them back through the public
// API, and checks the round-tripped pixels against computed expectations with
// tight numeric tolerances (gamma, transforms). It uses only the library's
// PUBLIC C ABI, so the same suite runs against the C reference or a translated
// Rust cdylib.
//
// pngvalid organizes its work into four groups (--standard, --size,
// --transform, --gamma), each a loop over thousands of independent scenarios.
// glue/glue_pngvalid.c walks those loops and reports one verdict per scenario;
// this file turns each scenario into its own GoogleTest case, so a defect
// costs the scenarios it actually breaks instead of a whole group.
//
// Each group is one value-parameterized test suite whose parameter is the
// scenario index, instantiated over the whole group. The instantiation name is
// left empty so the group name alone is the gtest suite name
// (`LibpngSize.Scenario/S00042_...`), which is what manifest.json filters on.
//
// The scenario names come from glue/scenario_list.h, a checked-in table
// regenerated by glue/dump_scenarios.c. Registration therefore executes no
// pngvalid code and touches the library under test not at all: a library
// broken enough to break enumeration fails all 6521 tests instead of leaving
// the suite reporting none, which the harness would read as broken
// infrastructure rather than as a score of zero. The table is kept honest by
// the recording run, which reports how many scenarios it visited; a
// disagreement fails every test of the group with a "stale" message rather
// than scoring verdicts that may belong to other scenarios.
//
// Each group runs in one process (see manifest.json): the first of its tests
// to run triggers the recording run, and the rest read that record.

#include <gtest/gtest.h>

#include <string>

#include "pv_record.h"
#include "scenario_list.h"

namespace {

// Shared body of every scenario test. The parameter is the scenario's index
// within its group; the group itself is fixed by the subclass below.
class ScenarioTestBase : public testing::TestWithParam<int> {
 protected:
  void Check(int group) {
    const int index = GetParam();

    ASSERT_EQ(pv_ensure_recorded(group, pv_scenario_counts[group]), 0)
        << "could not run the recording pass for "
        << harvest_pngvalid_group_suite(group);

    // A completed run that visited a different number of scenarios than the
    // checked-in list holds means upstream's loops moved: every verdict below
    // may be attributed to the wrong scenario, so say so instead of scoring.
    if (pv_run_completed(group) &&
        pv_recorded_count(group) != pv_scenario_counts[group]) {
      FAIL() << "glue/scenario_list.h is stale for "
             << harvest_pngvalid_group_suite(group) << ": the recording run "
             << "visited " << pv_recorded_count(group)
             << " scenarios, the list has " << pv_scenario_counts[group]
             << ". Regenerate it (see glue/dump_scenarios.c).";
    }

    switch (pv_verdict(group, index)) {
      case PV_PASSED:
        return;
      case PV_FAILED:
        FAIL() << pv_failure(group, index);
      case PV_NOT_REACHED:
        // Reported as a failure, never a skip: a skip would leave the
        // harness's denominator and let an early crash score better than a
        // late one.
        FAIL() << "NOT_REACHED: the recording run ended before this scenario "
                  "(the library under test crashed, hung, or hit its budget)";
    }
  }
};

// Test name suffix for one scenario: its name from the checked-in table.
// GoogleTest requires these to be unique and to hold only alphanumerics and
// underscores, which is what the generator sanitizes them to.
template <int Group>
std::string ScenarioName(const testing::TestParamInfo<int>& info) {
  return pv_scenario_names[Group][info.param];
}

}  // namespace

// One value-parameterized suite per pngvalid group, instantiated over every
// scenario the checked-in list holds for it. The empty instantiation name
// keeps the group name as the gtest suite name.
#define LIBPNG_SCENARIO_GROUP(Name, GroupId)                             \
  class Name : public ScenarioTestBase {};                               \
  TEST_P(Name, Scenario) { Check(GroupId); }                             \
  INSTANTIATE_TEST_SUITE_P(, Name,                                       \
                           testing::Range(0, pv_scenario_counts[GroupId]), \
                           ScenarioName<GroupId>)

LIBPNG_SCENARIO_GROUP(LibpngStandard, PV_GROUP_STANDARD);
LIBPNG_SCENARIO_GROUP(LibpngSize, PV_GROUP_SIZE);
LIBPNG_SCENARIO_GROUP(LibpngTransform, PV_GROUP_TRANSFORM);
LIBPNG_SCENARIO_GROUP(LibpngGamma, PV_GROUP_GAMMA);
