// Scenario tables for the zstd unit-test monoliths.
//
// Each entry is one `DISPLAYLEVEL(3, "test%3i : <desc> : ", testNb++)` banner
// upstream prints. The tables were captured from a run against the reference C
// library (ids are upstream's own testNb, which is sparse because a few
// scenarios are compiled out with ZSTD_MULTITHREAD). They fix the set of
// reported scenarios — and therefore the harness's denominator — independently
// of how far a given library under test actually gets.
//
// C++ only: the translation units that include upstream sources are C and do
// not need these tables. Descriptions are string literals, so `.data()` is
// NUL-terminated and safe to hand back across the C interface in scenarios.cc.
